// Icon renders a Lucide icon at the given size in logical pixels.
func Icon(name string, c gc.Hsla, size float32) gpui.Element {
	rgb := c.ToRgb()
	svg := fmt.Sprintf(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="rgb(%d,%d,%d)" stroke-opacity="%g" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">%s</svg>`,
		int(rgb.R*255), int(rgb.G*255), int(rgb.B*255), rgb.A, lucideIcons[name])
	return elements.NewSvgFromData([]byte(svg)).W(Px(size)).H(Px(size)).FlexShrink(0)
}

func CheckIcon(c gc.Hsla) gpui.Element { return Icon("check", c, 13) }

func ChevronIcon(c gc.Hsla, expanded bool) gpui.Element {
	if expanded {
		return Icon("chevron-down", c, 12)
	}
	return Icon("chevron-right", c, 12)
}

func FolderIcon(c gc.Hsla, open bool) gpui.Element {
	if open {
		return Icon("folder-open", c, 14)
	}
	return Icon("folder", c, 14)
}

func FileIcon(c gc.Hsla) gpui.Element { return Icon("file", c, 14) }

